package src.main.java.delivery;

/**
 * Один заказ от начала до конца — таким, каким должен быть код,
 * когда в сервисе появятся все нужные классы.
 */
public class OrderScenario {
    public static void main(String[] args) {
        int now = 1290;                    // 21:30 — минут от полуночи
        Point client = new Point(7, 8);

        // 1. Клиент открывает «Пиццу Паоло» и видит, открыта ли она.
         Restaurant pizza = Restaurant.loadAll()[2];
         System.out.println("Ресторан: " + pizza.getName() + ", "
                 + (pizza.isOpen(now) ? "открыт" : "закрыт"));

        // 2. В корзину: Маргарита, 2 Тирамису, Лимонад. Клиент видит, что в корзине.
        //    ? Какой класс хранит корзину и что он получает при создании?
        //    ? Каким методом положить блюдо: что передаём — номер блюда или объект Dish, и
        //      количество?
        //    ? Тирамису положили ещё раз — появится вторая позиция или станет 3 шт.?

        // 3. Сумма корзины и минимальный заказ ресторана.
        //    ? Каким методом получить сумму корзины?
        //    ? Какой класс хранит минимальный заказ и какой класс сравнивает с ним сумму?
        //    ? Минимальный заказ не набран — что происходит: только сообщение или заказ
        //      нельзя оформить?

        // 4. Промокод WELCOME10.
        //    ? Промокод в коде — объект (код, вид скидки, размер, минимальная сумма) или
        //      просто строка?
        //    ? Какой класс применяет промокод? Метод возвращает скидку или новую сумму?
        //    ? Промокод не подходит (PIZZA300 действует от 1 500 ₽) — что будет?

        // 5. Доставка до клиента.
        //    ? Какой класс отвечает за цену доставки?
        //    ? Что ему нужно знать: откуда, куда, который час, сумму заказа?
        //    ? Бесплатно от 1 500 ₽ — от суммы до скидки или после?

        // 6. Курьер.
        //    ? Какой класс хранит всех курьеров и каким методом найти ближайшего свободного
        //      к ресторану?
        //    ? Как отметить, что курьер взял заказ, — что у него меняется?
        //    ? Свободных курьеров нет — что вернёт метод и что будет с заказом?

        // 7. Заказ целиком: итого, время, чек.
        //    ? Есть ли объект «заказ», который хранит корзину, промокод, доставку, курьера?
        //    ? Какой класс отвечает за «Итого», время готовки (самое долгое блюдо), дорогу
        //      и время прибытия?

        // 8. Сервис сохраняет каждый заказ, чтобы потом считать выручку и часы пик:
        //    new OrderRecord(час, сумма, номер клиента, номер ресторана).
        //    ? Какую сумму записать — до скидки, со скидкой или вместе с доставкой?
        //    ? Откуда взять номер клиента?
        //    ? Какой класс создаёт OrderRecord?
    }
}
